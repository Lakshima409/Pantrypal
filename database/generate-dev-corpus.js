#!/usr/bin/env node
// database/generate-dev-corpus.js
//
// Emits database/dev-corpus.sql — a small, DETERMINISTIC synthetic corpus so the
// stack can be exercised end-to-end on a fresh machine.
//
// WHY THIS EXISTS
//   schema.sql + migrations/ + seed.sql only create STRUCTURE plus the demo login.
//   The real corpus (10k recipes / 1k ingredients / 100k interactions) lived only
//   in the original author's local MySQL and was never committed. Without any rows
//   the recommender crashes on boot (TfidfVectorizer "empty vocabulary") and the
//   diet-planner tests fail with "min() iterable argument is empty".
//
// WHAT THIS IS NOT
//   Not real data and not a replacement for the source dataset. Every row is
//   tagged source_dataset='dev-corpus' so it is trivially identifiable and safe to
//   delete. Regenerate with: node database/generate-dev-corpus.js
//
// The SQL it produces is idempotent: DELETE by source_dataset first, then insert.

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

// Data lives in versioned JSON so this file stays readable and diffable.


const INGREDIENTS = require("./dev-corpus.ingredients.json").ingredients;
const TAGS = require("./dev-corpus.tags.json").tags;
const RECIPES = require("./dev-corpus.recipes.json").recipes;

// ---- SQL helpers -----------------------------------------------------------
const q = (v) => `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
const sha = (s) => crypto.createHash("sha256").update(s).digest("hex");

const out = [];
const push = (line) => out.push(line);

push("-- database/dev-corpus.sql");
push("-- GENERATED by database/generate-dev-corpus.js — do not edit by hand.");
push("-- Synthetic, deterministic development corpus so the recommender, the");
push("-- diet-planner and the user journeys run against a non-empty recipe_db.");
push("-- Every row is tagged source_dataset='dev-corpus' and is safe to delete.");
push("");
push("SET NAMES utf8mb4;");
push("SET FOREIGN_KEY_CHECKS = 0;");
push("USE recipe_db;");
push("");
push("-- Remove any previous load of this corpus so the file is re-runnable.");
push("DELETE FROM recipe_ingredients WHERE recipe_id IN (SELECT recipe_id FROM recipes WHERE source_dataset = 'dev-corpus');");
push("DELETE FROM recipe_tags        WHERE recipe_id IN (SELECT recipe_id FROM recipes WHERE source_dataset = 'dev-corpus');");
push("DELETE FROM nutrition_info     WHERE recipe_id IN (SELECT recipe_id FROM recipes WHERE source_dataset = 'dev-corpus');");
push("DELETE FROM interactions       WHERE recipe_id IN (SELECT recipe_id FROM recipes WHERE source_dataset = 'dev-corpus');");
push("DELETE FROM recipes            WHERE source_dataset = 'dev-corpus';");
push(`DELETE FROM tags        WHERE tag_name IN (${TAGS.map((t) => q(t[0])).join(",")});`);
push(`DELETE FROM ingredients WHERE name      IN (${INGREDIENTS.map((i) => q(i[0])).join(",")});`);
push("");

// ---- ingredients -----------------------------------------------------------
push("-- Ingredients");
for (const [name, category, unit, kcal, protein, fat, carbs, sodium] of INGREDIENTS) {
  push(
    `INSERT INTO ingredients (name, category, unit, calories_per_100g, protein_per_100g, ` +
      `fat_per_100g, carbs_per_100g, sodium_mg_per_100g, nutrition_source, is_nutrition_reference) ` +
      `VALUES (${q(name)}, ${q(category)}, ${q(unit)}, ${kcal}, ${protein}, ${fat}, ${carbs}, ` +
      `${sodium}, 'dev-corpus', 0) ON DUPLICATE KEY UPDATE category = VALUES(category);`
  );
}
push("");

// ---- tags ------------------------------------------------------------------
push("-- Tags");
for (const [name, type] of TAGS) {
  push(
    `INSERT INTO tags (tag_name, tag_type, is_candidate) VALUES (${q(name)}, ${q(type)}, 0) ` +
      `ON DUPLICATE KEY UPDATE tag_type = VALUES(tag_type);`
  );
}
push("");

// ---- recipes, nutrition, joins ---------------------------------------------
push("-- Recipes, nutrition and join rows");
const recipeIds = [];
RECIPES.forEach((recipe, index) => {
  const [title, ingIdx, tagNames, kcal, protein, fat, carbs] = recipe;
  // Explicit ids outside the real corpus range (real data started at 10001).
  const recipeId = 900001 + index;
  recipeIds.push(recipeId);

  const steps = JSON.stringify([
    `Prepare all ingredients for ${title}.`,
    "Cook over medium heat, seasoning to taste.",
    "Serve immediately and enjoy.",
  ]);
  push(
    `INSERT INTO recipes (recipe_id, title, instructions, created_by, source_dataset, source_id, ` +
      `dataset_license, content_sha256) VALUES (${recipeId}, ${q(title)}, ${q(steps)}, NULL, ` +
      `'dev-corpus', ${q(String(recipeId))}, 'synthetic-dev-fixture', ${q(sha(`dev-corpus:${recipeId}`))});`
  );
  push(
    `INSERT INTO nutrition_info (recipe_id, calories, protein, fat, carbs, sodium, servings, ` +
      `nutrition_basis, calculation_method) VALUES (${recipeId}, ${kcal}, ${protein}, ${fat}, ` +
      `${carbs}, 800, 4, 'whole_recipe', 'dev-corpus fixture');`
  );
  // Dedupe defensively: (recipe_id, ingredient_id) is UNIQUE, and a repeated
  // index would abort the whole load on a duplicate-key error.
  const ingIndexes = [...new Set(ingIdx)];
  for (const ingIndex of ingIndexes) {
    const name = INGREDIENTS[ingIndex][0];
    push(
      `INSERT INTO recipe_ingredients (recipe_id, ingredient_id, quantity, unit, original_text) ` +
        `SELECT ${recipeId}, i.ingredient_id, 100, i.unit, ${q(name)} FROM ingredients i ` +
        `WHERE i.name = ${q(name)};`
    );
  }
  for (const tag of tagNames) {
    push(
      `INSERT IGNORE INTO recipe_tags (recipe_id, tag_id) SELECT ${recipeId}, t.tag_id ` +
        `FROM tags t WHERE t.tag_name = ${q(tag)};`
    );
  }
  push("");
});

// ---- interactions ----------------------------------------------------------
// Gives the demo user and a few synthetic users a history so the
// collaborative-filtering (§22) and preference-affinity paths have signal.
// bcrypt hashes below are for password "Baseline123!" (dev fixture only).
push("-- Interaction history (drives CF + preference affinity, blueprint §8/§22)");
const SYNTHETIC_USERS = [
  ["Baseline One", "baseline1@pantrypal.local", "$2a$10$5nvr/6EAIp4djwbRsOB2FekGWtKUoccvR22qi0lL2Y8o5g4IVG34q"],
  ["Baseline Two", "baseline2@pantrypal.local", "$2a$10$b1ouysQw9TDxu9CKxID8yuSxlUZ/ENUBQ2MgP8yLPK4A1522EJU.G"],
  ["Baseline Three", "baseline3@pantrypal.local", "$2a$10$/xV20m3Dv2VHNUrLKtcgNOPPhbQf1KyrBc6ZExz0JV0aKRf3qvOwO"],
];
push(
  `INSERT INTO users (name, email, password_hash) VALUES ` +
    SYNTHETIC_USERS.map(([n, e, h]) => `(${q(n)}, ${q(e)}, ${q(h)})`).join(",") +
    ` ON DUPLICATE KEY UPDATE name = VALUES(name);`
);
push("");

// Deterministic PRNG (fixed seed) keeps the generated SQL byte-stable.
let seed = 12345;
const rand = () => {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed / 0x7fffffff;
};
const TYPES = ["viewed", "viewed", "viewed", "liked", "saved", "cooked"];
// Shared anchors guarantee the user-user CF path always has neighbours.
const ANCHORS = [900001, 900010];

push("SET @demo := (SELECT user_id FROM users WHERE email = 'demo@pantrypal.local');");
for (const [, email] of SYNTHETIC_USERS) {
  push(`SET @u := (SELECT user_id FROM users WHERE email = ${q(email)});`);
  const picked = new Set(ANCHORS);
  for (const anchor of ANCHORS) {
    push(`INSERT INTO interactions (user_id, recipe_id, type) VALUES (@u, ${anchor}, 'liked');`);
  }
  for (let n = 0; n < 18; n += 1) {
    const recipeId = recipeIds[Math.floor(rand() * recipeIds.length)];
    if (picked.has(recipeId)) continue;
    picked.add(recipeId);
    const type = TYPES[Math.floor(rand() * TYPES.length)];
    push(`INSERT INTO interactions (user_id, recipe_id, type) VALUES (@u, ${recipeId}, ${q(type)});`);
  }
  push("");
}
push(
  `INSERT INTO interactions (user_id, recipe_id, type) VALUES ` +
    `(@demo, 900001, 'liked'), (@demo, 900005, 'viewed'), (@demo, 900010, 'cooked');`
);
push("");
push("SET FOREIGN_KEY_CHECKS = 1;");
push("-- dev-corpus.sql: end");

// ---- write -----------------------------------------------------------------
const target = path.join(__dirname, "..", "database", "dev-corpus.sql");
fs.writeFileSync(target, out.join("\n") + "\n", "utf8");
console.log(
  `Wrote ${target}\n  ${INGREDIENTS.length} ingredients, ${TAGS.length} tags, ` +
    `${RECIPES.length} recipes, ${SYNTHETIC_USERS.length} synthetic users`
);
